# make-app-manifest.ps1 -- write site/app.json from the setups installer-build.ps1 produced.
#
# ASCII only. CRLF. Must parse and run on Windows PowerShell 5.1 and PowerShell 7+.
# No ternary operator, no null-coalescing, no '&&' inside this file.
# (The house rule is release-build.ps1:3-4. Japanese lives in installer/irodori-tts-ywk.iss only.)
#
# Canon   : decisions.md 160 (the in-app update sequence, 2026-09-24).
# Design  : docs/design/app-update.md. Reference shape: yomiwakechan2 tools/publish-app-release.ps1.
#
# What it does (and nothing else):
#   0  read the version from the ONE place that defines it (launcher/Directory.Build.props).
#   1  find build/out/installer/irodori-tts-ywk-setup-<ver>-cuda.exe and -radeon.exe.
#   2  sha256 + bytes of the artefacts THEMSELVES, and cross-check SHA256SUMS.txt if a line is
#      there (installer-build.ps1 only writes a line for a setup that passed its gates -- a
#      disagreement means the exe on disk is not the one that was inspected, so we stop).
#   3  write site/app.json (UTF-8 without BOM, LF), then parse it back before claiming success.
#
# It does NOT upload, tag, commit or push anything. The release order is fixed and is written
# out at the end of every run (site/README.md has the same list):
#   1) the GitHub Release assets go up FIRST,
#   2) app.json is regenerated by this script and site/ is pushed to gh-pages -- THAT push is the
#      switch that makes the in-app update visible. Assets first, manifest last; if a run stops in
#      between, the world only ever sees "assets are there, app.json still names the old version".
#
# Usage:
#   pwsh -NoProfile -ExecutionPolicy Bypass -File build/make-app-manifest.ps1
#   pwsh ... -File build/make-app-manifest.ps1 -Note "GPU memory fix"
#   pwsh ... -File build/make-app-manifest.ps1 -OutDir D:\somewhere\installer

[CmdletBinding()]
param(
    [string]$OutDir = '',
    [string]$ManifestPath = '',
    [string]$Note = '',
    [string]$BuiltAt = '',
    [switch]$AllowMissingSums
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

. (Join-Path $PSScriptRoot 'Common.ps1')

# The manifest contract (docs/design/app-update.md section 2). These four strings are the
# contract with the launcher: Services/Update/AppDistributionContract.cs spells the same ones.
$SchemaVersion = 1
$AppName       = 'irodori-tts-ywk'
$PageUrl       = 'https://mugonkun.github.io/irodori-tts-for-yomiwakechan/'
$ReleaseBase   = 'https://github.com/mugonkun/irodori-tts-for-yomiwakechan/releases/download/'
$Flavors       = @('cuda', 'radeon')

$repo = Get-YwkRepoRoot
if ([string]::IsNullOrEmpty($OutDir)) {
    $OutDir = Join-Path $repo 'build\out\installer'
}
if ([string]::IsNullOrEmpty($ManifestPath)) {
    $ManifestPath = Join-Path $repo 'site\app.json'
}

Write-Host '=== make-app-manifest ==='
Write-Host ('  setups   : ' + $OutDir)
Write-Host ('  manifest : ' + $ManifestPath)

# ---------------------------------------------------------------- stage 0: the version

$props = Join-Path $repo 'launcher\Directory.Build.props'
if (-not (Test-Path -LiteralPath $props)) {
    throw ('launcher/Directory.Build.props is missing: ' + $props)
}
$versionHits = @(Select-String -Path $props -Pattern '<AppDisplayVersion>(.+)</AppDisplayVersion>')
if ($versionHits.Count -ne 1) {
    throw ('Directory.Build.props has ' + $versionHits.Count +
        ' AppDisplayVersion tags (expected exactly 1 -- the version has one definition).')
}
$appVersion = $versionHits[0].Matches[0].Groups[1].Value.Trim()
if ($appVersion -notmatch '^v[0-9]') {
    throw ('AppDisplayVersion is "' + $appVersion + '"; the manifest needs the v-prefixed display ' +
        'form (the launcher compares it to AppVersion.Display as a plain string).')
}
Write-Host ('  version  : ' + $appVersion)

# ---------------------------------------------------------------- stage 1+2: the artefacts

$sumsPath = Join-Path $OutDir 'SHA256SUMS.txt'
$sums = @{}
if (Test-Path -LiteralPath $sumsPath) {
    foreach ($line in @(Get-Content -LiteralPath $sumsPath -Encoding UTF8)) {
        $t = $line.Trim()
        if ($t.Length -eq 0) { continue }
        # installer-build.ps1 writes the sha256sum convention: "<sha256>  <name>".
        $parts = @($t -split '\s+', 2)
        if ($parts.Count -eq 2) {
            $sums[$parts[1].Trim()] = $parts[0].Trim().ToLowerInvariant()
        }
    }
} elseif (-not $AllowMissingSums) {
    throw ('SHA256SUMS.txt is missing (' + $sumsPath + '). Run build/installer-build.ps1 -All ' +
        'first, or pass -AllowMissingSums if you know why it is not there.')
}

$installers = [ordered]@{}
foreach ($fl in $Flavors) {
    $name = 'irodori-tts-ywk-setup-' + $appVersion + '-' + $fl + '.exe'
    $path = Join-Path $OutDir $name
    if (-not (Test-Path -LiteralPath $path)) {
        throw ('the ' + $fl + ' setup is missing: ' + $path +
            ' (build/installer-build.ps1 -All writes both flavours).')
    }

    $sha = Get-YwkSha256 -Path $path
    $size = Get-YwkFileSize -Path $path

    if ($sums.ContainsKey($name)) {
        if ($sums[$name] -ne $sha) {
            throw ('SHA256SUMS.txt and ' + $name + ' disagree (file = ' + $sha + ', sums = ' +
                $sums[$name] + '). The exe on disk is not the one the gates inspected -- rebuild.')
        }
    } elseif (-not $AllowMissingSums) {
        throw ($name + ' has no line in SHA256SUMS.txt. installer-build.ps1 only records a setup ' +
            'that passed gates B-1/B-2, so an absent line means this exe was rejected or is stale.')
    }

    Write-Host ('  ' + $fl + ' : ' + $sha + '  ' + $size + ' B')
    $installers[$fl] = [ordered]@{
        url       = $ReleaseBase + $appVersion + '/' + $name
        sha256    = $sha
        sizeBytes = $size
    }
}

# ---------------------------------------------------------------- stage 3: write and read back

$builtAtValue = $BuiltAt
if ([string]::IsNullOrEmpty($builtAtValue)) {
    $builtAtValue = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
}
$noteValue = $null
if (-not [string]::IsNullOrEmpty($Note)) {
    $noteValue = $Note
}

$doc = [ordered]@{
    v          = $SchemaVersion
    name       = $AppName
    version    = $appVersion
    builtAt    = $builtAtValue
    pageUrl    = $PageUrl
    note       = $noteValue
    installers = $installers
}

$json = $doc | ConvertTo-Json -Depth 8
# app.json IS the publication switch: a broken one takes the whole in-app update path down with
# it, so nothing is written until the text we are about to write has parsed as JSON.
try {
    $read = $json | ConvertFrom-Json
} catch {
    throw ('the manifest we built is not valid JSON: ' + $_.Exception.Message)
}
if ($read.v -ne $SchemaVersion) { throw 'the manifest lost its "v".' }
if ($read.name -ne $AppName) { throw 'the manifest lost its "name".' }
if ($read.version -ne $appVersion) { throw 'the manifest lost its "version".' }
foreach ($fl in $Flavors) {
    $entry = $read.installers.$fl
    if ($null -eq $entry) { throw ('the manifest lost the ' + $fl + ' installer.') }
    if ($entry.url -notlike 'https://*') { throw ('the ' + $fl + ' url is not https.') }
    if ($entry.sha256 -notmatch '^[0-9a-f]{64}$') { throw ('the ' + $fl + ' sha256 is not 64 hex.') }
}

$null = Write-YwkTextFile -Path $ManifestPath -Text ($json + "`n") -Newline 'LF'
Write-Host ''
Write-Host ('WROTE ' + $ManifestPath + ' (' + $appVersion + ')')
Write-Host ''
Write-Host 'Release order (site/README.md says the same thing):'
Write-Host '  1. upload the two setups as GitHub Release assets for the tag first;'
Write-Host '  2. run this script, then push site/ to gh-pages -- THAT push is the switch that'
Write-Host '     makes the in-app update visible. Never the other way round.'
exit 0
